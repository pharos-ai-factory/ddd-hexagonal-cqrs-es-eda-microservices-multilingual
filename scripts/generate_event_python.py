"""Generate plain published Python DTOs and typed adaptor conversions."""

HEADER = "# Generated by scripts/generate_events.py. DO NOT EDIT.\n"


def generate(root, messages, events):
    base = root / "services/operations/src/operations"
    (base / "adaptors/generated").mkdir(parents=True, exist_ok=True)
    dto_root = base / "contracts/events/generated"
    dto_root.mkdir(parents=True, exist_ok=True)
    (dto_root / "__init__.py").write_text(
        '"""Generated plain published event contracts, grouped by producer."""\n'
    )
    for path in dto_root.glob("*.py"):
        if path.name != "__init__.py":
            path.unlink()
    for path in (base / "adaptors/generated").glob("event_*.py"):
        path.unlink()
    for owner in sorted({m["owner"] for m in messages}):
        owned = [m for m in messages if m["owner"] == owner]
        dtos = [HEADER, "from __future__ import annotations\nfrom typing import TypedDict\n\n"]
        foreign = {
            f["message"].split(".")[-1]
            for m in owned
            for f in m["fields"]
            if f["message"] and not any(other["type"] == f["message"] for other in owned)
        }
        for name in sorted(foreign):
            source = next(m for m in messages if m["name"] == name)
            dtos.append(f"from .{source['owner']} import {name}\n")
        codecs = [
            HEADER,
            "from google.protobuf.message import Message\n",
            "from operations.adaptors.event_payload import parse_payload\n",
            "from operations.foundation.application import Publication\n",
            f"from operations.contracts.events.generated.{owner} import {', '.join(m['name'] for m in owned)}\n",
        ]
        for source in sorted({m["source"] for m in owned}):
            module = source.removesuffix(".proto").replace("/", ".") + "_pb2"
            codecs.append(
                f"from operations.adaptors.generated.{module} import {', '.join(m['name'] + ' as Wire' + m['name'] for m in owned if m['source'] == source)}\n"
            )
        for name in sorted(foreign):
            source = next(m for m in messages if m["name"] == name)
            codecs.append(f"from .event_{source['owner']} import from_{name}\n")
        for m in owned:
            name = m["name"]
            dtos.append(f'\n\nclass {name}(TypedDict):\n    """Published {name} data owned by {owner}."""\n')
            codecs.append(f"\n\ndef from_{name}(value: Wire{name}) -> {name}:\n    return {name}(\n")
            for f in m["fields"]:
                typ = (
                    f["message"].split(".")[-1]
                    if f["type"] == 11
                    else {9: "str", 8: "bool"}.get(f["type"], "int")
                )
                if f["repeated"]:
                    typ = "list[" + typ + "]"
                dtos.append(f"    {f['json']}: {typ}\n")
                value = "value." + f["name"]
                if f["type"] == 11:
                    target = "from_" + f["message"].split(".")[-1]
                    value = f"[{target}(item) for item in {value}]" if f["repeated"] else f"{target}({value})"
                codecs.append(f"        {f['json']}={value},\n")
            codecs.append("    )\n")
            event = next((e for e in events if e["type"] == m["type"]), None)
            if event:
                codecs.append(
                    f"\n\ndef publish_{name}(payload: {name}) -> Publication:\n"
                    f"    return Publication({event['name']!r}, payload)\n"
                )
                codecs.append(
                    f"\n\ndef decode_{name}(body: bytes, aggregate_id: str) -> {name}:\n"
                    f"    value = Wire{name}()\n    parse_payload(value, body, aggregate_id)\n"
                    f"    return from_{name}(value)\n"
                )
        # Only top-level payloads need the parsing helper; all generated schemas have one here.
        (dto_root / (owner + ".py")).write_text("".join(dtos))
        (base / f"adaptors/generated/event_{owner}.py").write_text(
            "".join(codecs).replace("from google.protobuf.message import Message\n", "")
        )
    registry = [HEADER, "from operations.adaptors.event_payload import PayloadCodec\n"]
    for event in events:
        name = event["type"].split(".")[-1]
        registry.append(f"from .event_{event['owner']} import decode_{name}, Wire{name}\n")
    registry.append("\nPAYLOAD_CODECS: dict[str, PayloadCodec] = {\n")
    for e in events:
        name = e["type"].split(".")[-1]
        registry.append(
            f"    {e['name']!r}: PayloadCodec({e['owner']!r}, {e['kind']!r}, {e['version']}, Wire{name}, decode_{name}),\n"
        )
    registry.append("}\n")
    (base / "adaptors/generated/event_registry.py").write_text("".join(registry))
