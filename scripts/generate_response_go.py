"""Generate plain Go responses, checked encoders and typed query bindings."""

from generate_event_go import field_name, MODULE

HEADER = "// Code generated by scripts/generate_response_payloads.py. DO NOT EDIT.\n"


def generate(root, owner, messages, requests, catalogue):
    shared = owner == "shared"
    models = [HEADER, f"package {owner}\n"]
    if not shared:
        models += [f'import shared "{MODULE}/contracts/requests/generated/model/shared"\n']
    codecs = [
        HEADER,
        "package responses\n" if shared else "package messaging\n",
        "import (\n",
        '"fmt"\n',
        f'model "{MODULE}/contracts/requests/generated/model/{owner}"\n',
    ]
    codecs += [
        f'pb "{MODULE}/contracts/requests/generated/cafe/requests/v1/{"shared" if shared else "contexts/" + owner}"\n'
    ]
    if not shared:
        codecs += [
            f'sharedwire "{MODULE}/adaptors/messaging/generated/responses"\n',
            f'wire "{MODULE}/contracts/requests/generated/cafe/requests/v1"\n',
        ]
    codecs += [")\n"]
    bindings = (
        [
            HEADER,
            'package queryregistration\nimport (\n"context"\n',
            f'requests "{MODULE}/adaptors/messaging/requests"\n',
            f'codec "{MODULE}/contexts/{owner}/adaptors/messaging"\n',
            f'model "{MODULE}/contracts/requests/generated/model/{owner}"\n',
            f'pb "{MODULE}/contracts/requests/generated/cafe/requests/v1/contexts/{owner}"\n',
            f'wire "{MODULE}/contracts/requests/generated/cafe/requests/v1"\n)\n',
        ]
        if not shared
        else []
    )
    for message in messages:
        name = message["name"]
        models += [f"// {name} is a schema-generated plain response payload.\ntype {name} struct {{\n"]
        for f in message["fields"]:
            typ = {3: "int64", 4: "uint64", 5: "int", 8: "bool", 9: "string", 13: "int"}.get(f["type"])
            if f["type"] == 11:
                target = catalogue[f["target"]]
                typ = ("shared." if target["owner"] == "shared" and not shared else "") + target["name"]
            typ = ("[]" if f["repeated"] else "*" if f["optional"] else "") + typ
            models += [
                f' {field_name(f["name"])} {typ} `json:"{f["json"]}{",omitempty" if f["optional"] else ""}"`\n'
            ]
        models += ["}\n"]
        codecs += [
            f"// To{name} encodes a plain response, preserving presence and numeric bounds.\n",
            f"func To{name}(value model.{name}) (*pb.{name}, error) {{\n result := &pb.{name}{{}}\n",
        ]
        for f in message["fields"]:
            field, wire = field_name(f["name"]), field_name(f["name"], True)
            expr = f"value.{field}"
            if f["repeated"]:
                codecs += [f" for _, item := range value.{field} {{\n"]
                expr = "item"
            elif f["optional"]:
                codecs += [f" if value.{field} != nil {{\n"]
                expr = "*" + expr
            if f["type"] == 11:
                target = catalogue[f["target"]]
                prefix = "sharedwire." if target["owner"] == "shared" and not shared else ""
                codecs += [
                    f" converted{field}, err := {prefix}To{target['name']}({expr}); if err != nil {{ return nil, err }}\n"
                ]
                expr = "converted" + field
            elif f["type"] in (3, 4, 5, 13):
                lo, hi = {
                    3: (-(2**53 - 1), 2**53 - 1),
                    4: (0, 2**53 - 1),
                    5: (-(2**31), 2**31 - 1),
                    13: (0, 2**32 - 1),
                }[f["type"]]
                codecs += [
                    f' if {expr} < {lo} || {expr} > {hi} {{ return nil, fmt.Errorf("{name}.{field}: integer outside schema range") }}\n'
                ]
                if f["type"] in (5, 13):
                    expr = f"{'int32' if f['type'] == 5 else 'uint32'}({expr})"
            if f["repeated"]:
                codecs += [f" result.{wire} = append(result.{wire}, {expr})\n }}\n"]
            elif f["optional"]:
                if f["type"] != 11:
                    codecs += [f" converted{field} := {expr}\n"]
                    expr = "&converted" + field
                codecs += [f" result.{wire} = {expr}\n }}\n"]
            else:
                codecs += [f" result.{wire} = {expr}\n"]
        codecs += [" return result, nil\n}\n"]
    for req in requests:
        name = req["name"].removesuffix(req["role"]) + "Response"
        target = catalogue[req["response"]]
        if req["role"] == "Command":
            models += [
                f"// {name} is the declared committed command outcome.\ntype {name} = shared.Outcome\n"
            ]
            continue
        field = field_name(req["response_field"])
        models += [
            f"// {name} selects this query's success payload or a request error.\ntype {name} struct {{\n {field} *{target['name']}\n Error *shared.RequestError\n}}\n"
        ]
        action = req["wire_name"]
        codecs += [
            f"// Encode{action}Response enforces the query's declared response alternatives.\n",
            f"func Encode{action}Response(_ model.{req['name']}, value model.{name}) (wire.Reply, error) {{\n",
            f' if (value.{field} == nil) == (value.Error == nil) {{ return nil, fmt.Errorf("{name}: select exactly one response") }}\n',
            " if value.Error != nil { item, err := sharedwire.ToRequestError(*value.Error); if err != nil { return nil, err }; return &pb.Reply{Payload: &pb.Reply_Error{Error: item}}, nil }\n",
            f" item, err := To{target['name']}(*value.{field}); if err != nil {{ return nil, err }}\n",
            f" return &pb.Reply{{Payload: &pb.Reply_{field}{{{field}: item}}}}, nil\n}}\n",
        ]
        bindings += [
            f"// Register{action} binds the schema's request, result and reply encoder.\n",
            f"func Register{action}(registry *requests.RabbitMQRequestRegistry, parse func(*pb.{action}) model.{req['name']}, execute func(context.Context, model.{req['name']}) (model.{name}, error)) {{\n",
            f" requests.Query(registry, wire.{owner.title()}Query{action}, parse, execute, codec.Encode{action}Response)\n}}\n",
        ]
    base = root / f"services/storefront/contracts/requests/generated/model/{owner}"
    base.mkdir(parents=True, exist_ok=True)
    (base / "responses.go").write_text("".join(models))
    dest = root / (
        "services/storefront/adaptors/messaging/generated/responses/responses.go"
        if shared
        else f"services/storefront/contexts/{owner}/adaptors/messaging/request_responses_generated.go"
    )
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("".join(codecs))
    if bindings:
        path = dest.parent / "generated" / "queryregistration" / "responses.go"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("".join(bindings))
