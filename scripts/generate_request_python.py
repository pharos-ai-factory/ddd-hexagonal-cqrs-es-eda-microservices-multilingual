"""Generate plain Python command/query types and typed owner mappings."""

import re
import ast

HEADER = "# Generated by scripts/generate_request_payloads.py. DO NOT EDIT.\n"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def clean_imports(source):
    tree = ast.parse(source)
    used = {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}
    lines = source.splitlines(keepends=True)
    for node in reversed(tree.body):
        if isinstance(node, ast.ImportFrom):
            names = [alias for alias in node.names if (alias.asname or alias.name) in used]
            replacement = (
                (
                    "from "
                    + node.module
                    + " import "
                    + ", ".join(a.name + (" as " + a.asname if a.asname else "") for a in names)
                    + "\n"
                )
                if names
                else ""
            )
            lines[node.lineno - 1 : node.end_lineno] = [replacement]
    return "".join(lines)


def generate(root, owner, messages):
    shared = owner == "shared"
    models = [HEADER, "from dataclasses import dataclass\nfrom typing import TypedDict, NotRequired\n"]
    if not shared:
        models += ["from operations.contracts.requests.generated.shared import PageRequest\n"]
    codecs = [
        HEADER,
        "from google.protobuf.message import Message\n",
        "from operations.foundation.domain import record\n",
        "from operations.adaptors.messaging.request_values import string_value, integer_value, boolean_value\n",
        f"from operations.contracts.requests.generated.{owner} import "
        + ", ".join(m["name"] for m in messages)
        + "\n",
        "from operations.contracts.requests.generated.shared import PageRequest\n",
    ]
    for m in messages:
        command = m["role"] == "Command"
        if not command:
            models += ["\n@dataclass(frozen=True)\n"]
        models += [
            f"\nclass {m['name']}{'(TypedDict)' if command else ''}:\n",
            f'    """Schema-defined {m["visibility"].lower()} {m["role"].lower()} payload."""\n',
        ]
        for f in sorted(m["fields"], key=lambda field: field["optional"]):
            typ = {3: "int", 4: "int", 5: "int", 8: "bool", 9: "str", 11: "PageRequest", 13: "int"}[f["type"]]
            suffix = ""
            if f["optional"]:
                if command:
                    typ = f"NotRequired[{typ}]"
                else:
                    typ += " | None"
                    suffix = " = None"
            models += [f"    {f['json'] if command else f['name']}: {typ}{suffix}\n"]
        if shared:
            continue
        name = m["name"]
        parse = "parse_" + snake(name)
        codecs += [
            f"\ndef {parse}(value: object) -> {name}:\n    {'data = ' if m['fields'] else ''}record(value)\n"
        ]
        fields = []
        for f in m["fields"]:
            key = repr(f["json"])
            # Non-presence proto3 fields carry their scalar default after decoding.
            default = '""' if f["type"] == 9 else ("False" if f["type"] == 8 else "0")
            access = f"data[{key}]" if f["required"] or f["optional"] else f"data.get({key}, {default})"
            if f["type"] == 11:
                expression = f"_page({access})"
            elif f["type"] == 9:
                expression = f"string_value({access})"
            elif f["type"] == 8:
                expression = f"boolean_value({access})"
            else:
                lo, hi = {
                    3: (-(2**53 - 1), 2**53 - 1),
                    4: (0, 2**53 - 1),
                    5: (-(2**31), 2**31 - 1),
                    13: (0, 2**32 - 1),
                }[f["type"]]
                expression = f"integer_value({access}, {lo}, {hi})"
            if f["optional"] and not command:
                expression = f"{expression} if {key} in data else None"
            fields.append((f, expression))
        values = [
            f"{f['json'] if command else f['name']}={expr}"
            for f, expr in fields
            if not (command and f["optional"])
        ]
        codecs += [f"    result = {name}(" + ", ".join(values) + ")\n"]
        for f, expr in fields:
            if command and f["optional"]:
                codecs += [f"    if {f['json']!r} in data:\n        result[{f['json']!r}] = {expr}\n"]
        codecs += ["    return result\n"]
        if m["visibility"] == "PUBLIC":
            module = f"operations.adaptors.generated.cafe.requests.v1.contexts.{owner}.{owner}_{'commands' if command else 'queries'}_pb2"
            codecs.insert(1, f"from {module} import {m['wire_name']} as Wire{name}\n")
            codecs += [
                f"\ndef {snake(m['wire_name'])}(value: Message) -> {name}:\n",
                f'    if not isinstance(value, Wire{name}):\n        raise ValueError("Unexpected {name} payload")\n',
                "    data: dict[str, object] = {}\n",
            ]
            for f in m["fields"]:
                name_f = f["name"]
                if f["required"]:
                    codecs += [
                        f'    if not value.HasField("{name_f}"):\n        raise ValueError("Missing required input: {name_f}")\n'
                    ]
                indent = "    "
                if f["optional"]:
                    codecs += [f'    if value.HasField("{name_f}"):\n']
                    indent += "    "
                if f["type"] == 11:
                    codecs += [
                        f'{indent}data[{f["json"]!r}] = {{"limit": value.{name_f}.limit, **({{"after": value.{name_f}.after}} if value.{name_f}.HasField("after") else {{}})}}\n'
                    ]
                else:
                    codecs += [f"{indent}data[{f['json']!r}] = value.{name_f}\n"]
            codecs += [f"    return {parse}(data)\n"]
    base = root / "services/operations/src/operations/contracts/requests/generated"
    base.mkdir(parents=True, exist_ok=True)
    (base / f"{owner}.py").write_text(clean_imports("".join(models)))
    if not shared:
        codecs += [
            "\ndef _page(value: object) -> PageRequest:\n    fields = record(value)\n",
            '    return PageRequest(integer_value(fields.get("limit", 0), 0, 4294967295), string_value(fields["after"]) if "after" in fields else None)\n',
        ]
        path = (
            root
            / f"services/operations/src/operations/contexts/{owner}/adaptors/messaging/generated/request_payloads.py"
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(clean_imports("".join(codecs)))
