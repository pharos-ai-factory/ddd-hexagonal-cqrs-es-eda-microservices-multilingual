"""Generated output paths remain recognisable without opening their contents."""

import unittest
from generated_files import STANDARD_NAMES, violation


class GeneratedFileTests(unittest.TestCase):
    def test_filename_or_generated_ancestor_identifies_an_output(self):
        for path in (
            "services/example/generated.json",
            "services/example/model_generated.go",
            "services/example/generated/events/payload.py",
        ):
            with self.subTest(path=path):
                self.assertIsNone(violation(path, "", classified=True))

    def test_unmarked_outputs_and_similarly_named_folders_fail(self):
        for path in (
            "services/example/events/payload.py",
            "services/example/generated-events/payload.json",
            "services/example/events/__init__.py",
        ):
            with self.subTest(path=path):
                self.assertIn("generated file must", violation(path, "", classified=True))

    def test_headers_detect_generated_files_missing_from_the_inventory(self):
        for source in (
            "// Code generated by a compiler. DO NOT EDIT.\n",
            "# Generated by scripts/generate_events.py. DO NOT EDIT.\n",
            '"""Generated plain published event contracts, grouped by producer."""\n',
        ):
            with self.subTest(source=source):
                self.assertIsNotNone(violation("services/example/events/payload.py", source))

    def test_handwritten_generator_strings_are_not_output_headers(self):
        for source in (
            'HEADER = "// Code generated by a compiler. DO NOT EDIT.\\n"\n',
            "// Package protobuf handles the technical envelope around generated event payload bindings.\n",
            "/** Generated published bindings and owner-declared private payloads compose the graph. */\n",
        ):
            with self.subTest(source=source):
                self.assertIsNone(violation("scripts/generate_events.py", source))

    def test_standard_names_are_exact_exceptions(self):
        for path in STANDARD_NAMES:
            self.assertIsNone(violation(path, "", classified=True))
        self.assertIsNotNone(violation("services/example/next-env.d.ts", "", classified=True))


if __name__ == "__main__":
    unittest.main()
