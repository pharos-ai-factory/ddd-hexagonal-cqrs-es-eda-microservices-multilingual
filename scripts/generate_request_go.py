"""Generate plain Go requests and owner-local Protobuf payload conversions."""

from generate_event_go import field_name, MODULE

HEADER = "// Code generated by scripts/generate_request_payloads.py. DO NOT EDIT.\n"


def generate(root, owner, messages):
    shared = owner == "shared"
    types = [HEADER, f"package {owner}\n"]
    if any(f["type"] == 11 for m in messages for f in m["fields"]):
        types += [f'import shared "{MODULE}/contracts/requests/generated/model/shared"\n']
    codecs = [
        HEADER,
        "package messaging\n",
        "import (\n",
        f' model "{MODULE}/contracts/requests/generated/model/{owner}"\n',
    ]
    if any(m["visibility"] == "PUBLIC" for m in messages):
        codecs += [f' pb "{MODULE}/contracts/requests/generated/cafe/requests/v1/contexts/{owner}"\n']
    if any(m["visibility"] == "PRIVATE" for m in messages):
        codecs += [f' private "{MODULE}/contexts/{owner}/adaptors/messaging/generated"\n']
    if not shared:
        codecs += [
            f' plain "{MODULE}/contracts/requests/generated/model/shared"\n',
            f' wire "{MODULE}/contracts/requests/generated/cafe/requests/v1/shared"\n',
        ]
    if any(
        m["visibility"] == "PRIVATE" and any(f["type"] in (3, 4, 5, 13) for f in m["fields"])
        for m in messages
    ):
        codecs += [' "fmt"\n']
    codecs += [")\n"]
    for m in messages:
        types += [
            f"// {m['name']} is the schema-defined {m['visibility'].lower()} {m['role'].lower()} payload.\n",
            f"type {m['name']} struct {{\n",
        ]
        for f in m["fields"]:
            typ = {
                3: "int64",
                4: "uint64",
                5: "int",
                8: "bool",
                9: "string",
                11: "shared.PageRequest",
                13: "int",
            }[f["type"]]
            types += [
                f' {field_name(f["name"])} {"*" if f["optional"] else ""}{typ} `json:"{f["json"]}{",omitempty" if f["optional"] else ""}"`\n'
            ]
        types += ["}\n"]
        if shared:
            continue
        wire_package = "pb" if m["visibility"] == "PUBLIC" else "private"
        function = m["wire_name"] if m["visibility"] == "PUBLIC" else "From" + m["name"]
        codecs += [
            f"// {function} converts a validated wire payload to its plain contract.\n",
            f"func {function}(value *{wire_package}.{m['wire_name']}) model.{m['name']} {{\n",
            f" result := model.{m['name']}{{}}\n",
        ]
        for f in m["fields"]:
            field, wire = field_name(f["name"]), field_name(f["name"], True)
            if f["type"] == 11:
                codecs += [f" result.{field} = fromRequestPage(value.Get{wire}())\n"]
            elif f["optional"]:
                expr = f"*value.{wire}"
                if f["type"] in (5, 13):
                    expr = f"int({expr})"
                codecs += [f" if value.{wire} != nil {{ v := {expr}; result.{field} = &v }}\n"]
            else:
                expr = f"value.Get{wire}()"
                if f["type"] in (5, 13):
                    expr = f"int({expr})"
                codecs += [f" result.{field} = {expr}\n"]
        codecs += [" return result\n}\n"]
        if m["visibility"] == "PRIVATE":
            codecs += [
                f"// To{m['name']} encodes the owner payload without its delivery metadata.\n",
                f"func To{m['name']}(value model.{m['name']}) (*private.{m['wire_name']}, error) {{\n",
                f" result := &private.{m['wire_name']}{{}}\n",
            ]
            for f in m["fields"]:
                field, wire = field_name(f["name"]), field_name(f["name"], True)
                expr = f"value.{field}"
                if f["optional"]:
                    codecs += [f" if value.{field} != nil {{\n"]
                    expr = "*" + expr
                if f["type"] in (3, 4, 5, 13):
                    lower, upper = {
                        3: (-(2**53 - 1), 2**53 - 1),
                        4: (0, 2**53 - 1),
                        5: (-(2**31), 2**31 - 1),
                        13: (0, 2**32 - 1),
                    }[f["type"]]
                    codecs += [
                        f' if {expr} < {lower} || {expr} > {upper} {{ return nil, fmt.Errorf("{field}: integer outside schema range") }}\n'
                    ]
                if f["type"] in (5, 13):
                    expr = f"{'int32' if f['type'] == 5 else 'uint32'}({expr})"
                if f["presence"]:
                    codecs += [f" v{field} := {expr}; result.{wire} = &v{field}\n"]
                else:
                    codecs += [f" result.{wire} = {expr}\n"]
                if f["optional"]:
                    codecs += [" }\n"]
            codecs += [" return result, nil\n}\n"]
    base = root / f"services/storefront/contracts/requests/generated/model/{owner}"
    base.mkdir(parents=True, exist_ok=True)
    (base / "payloads.go").write_text("".join(types))
    if not shared:
        codecs += [
            "func fromRequestPage(value *wire.PageRequest) *plain.PageRequest {\n",
            " if value == nil { return nil }; result := &plain.PageRequest{Limit: int(value.Limit)}\n",
            " if value.After != nil { after := *value.After; result.After = &after }; return result\n}\n",
        ]
        (
            root / f"services/storefront/contexts/{owner}/adaptors/messaging/request_payloads_generated.go"
        ).write_text("".join(codecs))
