"""Generate plain Go payloads and explicit Protobuf conversions per producer."""

import json
import re

HEADER = "// Code generated by scripts/generate_events.py. DO NOT EDIT.\n"
MODULE = (
    "github.com/pharos-ai-factory/ddd-hexagonal-cqrs-es-eda-microservices-multilingual/services/storefront"
)


def field_name(name, wire=False):
    return "".join(part.title() if wire or part != "id" else "ID" for part in name.split("_"))


def generate(root, messages, events):
    event_names = {e["type"].split(".")[-1] for e in events}

    def explicit_names(source, model_only=False):
        for name in sorted(event_names):
            pattern = (r"(?<=model\.)" if model_only else r"\b") + name + r"\b"
            source = re.sub(pattern, name + "IntegrationEvent", source)
        return source

    base = root / "services/storefront/contracts/events"
    for directory in ("model", "protobuf"):
        (base / directory).mkdir(parents=True, exist_ok=True)
        for path in (base / directory).glob("*_generated.go"):
            path.unlink()
    for owner in sorted({m["owner"] for m in messages}):
        owned = [m for m in messages if m["owner"] == owner]
        dtos = [HEADER, "package model\n"]
        imports = f'import (\n model "{MODULE}/contracts/events/model"\n pb "{MODULE}/contracts/events/generated/cafe/v1"\n'
        if any(e["type"] == m["type"] for e in events for m in owned):
            imports += f' a "{MODULE}/foundation/application"\n'
        if any(f["type"] == 5 for m in owned for f in m["fields"]):
            imports += ' "fmt"\n'
        codecs = [HEADER, "package protobuf\n", imports + ")\n"]
        for m in owned:
            name = m["name"]
            dtos.append(f"\n// {name} carries published data owned by {owner}.\ntype {name} struct {{\n")
            to_wire, from_wire = [], []
            for f in m["fields"]:
                typ = (
                    f["message"].split(".")[-1]
                    if f["type"] == 11
                    else {3: "int64", 4: "uint64", 5: "int", 8: "bool", 9: "string", 13: "uint32"}[f["type"]]
                )
                field, wire = field_name(f["name"]), field_name(f["name"], True)
                dtos.append(f' {field} {("[]" if f["repeated"] else "") + typ} `json:"{f["json"]}"`\n')
                if f["type"] == 11:
                    if f["repeated"]:
                        to_wire.append(
                            f" for _, item := range value.{field} {{ result.{wire} = append(result.{wire}, to{typ}(item)) }}\n"
                        )
                        from_wire.append(
                            f" result.{field} = make([]model.{typ}, 0, len(value.{wire}))\n for _, item := range value.{wire} {{ result.{field} = append(result.{field}, from{typ}(item)) }}\n"
                        )
                    else:
                        to_wire.append(f" result.{wire} = to{typ}(value.{field})\n")
                        from_wire.append(f" result.{field} = from{typ}(value.{wire})\n")
                else:
                    encoded = f"int32(value.{field})" if f["type"] == 5 else "value." + field
                    decoded = f"int(value.{wire})" if f["type"] == 5 else "value." + wire
                    to_wire.append(f" result.{wire} = {encoded}\n")
                    from_wire.append(f" result.{field} = {decoded}\n")
            dtos.append("}\n")
            codecs.extend(
                [
                    f"\nfunc to{name}(value model.{name}) *pb.{name} {{\n result := &pb.{name}{{}}\n",
                    *to_wire,
                    " return result\n}\n",
                    f"\nfunc from{name}(value *pb.{name}) model.{name} {{\n result := model.{name}{{}}\n",
                    *from_wire,
                    " return result\n}\n",
                ]
            )
            codecs.append(f"\nfunc check{name}Input(value model.{name}) error {{\n")
            for f in m["fields"]:
                field = field_name(f["name"])
                if f["type"] == 5:
                    codecs.append(
                        f' if value.{field} < -2147483648 || value.{field} > 2147483647 {{ return fmt.Errorf("int32 overflow: {field}") }}\n'
                    )
                if f["message"]:
                    target = f["message"].split(".")[-1]
                    if f["repeated"]:
                        codecs.append(
                            f" for _, item := range value.{field} {{ if err:=check{target}Input(item); err!=nil {{return err}} }}\n"
                        )
                    else:
                        codecs.append(
                            f" if err:=check{target}Input(value.{field}); err!=nil {{return err}}\n"
                        )
            codecs.append(" return nil\n}\n")
            event = next((e for e in events if e["type"] == m["type"]), None)
            if event:
                codecs.append(
                    f"\n// Publish{name} binds the published identity to its plain payload type.\nfunc Publish{name}(payload model.{name}) a.Publication {{\n return a.Publication{{Name: {json.dumps(event['name'])}, Visibility: a.Public, Payload: payload}}\n}}\n"
                )
        (base / f"model/{owner}_generated.go").write_text(explicit_names("".join(dtos)))
        (base / f"protobuf/{owner}_generated.go").write_text(explicit_names("".join(codecs), True))
    registry = [
        HEADER,
        "package protobuf\n",
        f'import (\n "fmt"\n "google.golang.org/protobuf/proto"\n model "{MODULE}/contracts/events/model"\n pb "{MODULE}/contracts/events/generated/cafe/v1"\n)\n',
        "var payloadCodecs = map[string]payloadCodec{\n",
    ]
    for e in events:
        name = e["type"].split(".")[-1]
        registry.append(f""" {json.dumps(e["name"])}: {{owner: {json.dumps(e["owner"])}, kind: {json.dumps(e["kind"])}, version: {e["version"]},
  encode: func(value any) (proto.Message, error) {{
   payload, ok := value.(model.{name}); if !ok {{ return nil, fmt.Errorf("event name and typed payload disagree") }}
   if err:=check{name}Input(payload); err!=nil {{return nil,err}}
   return to{name}(payload), nil
  }},
  decode: func(value proto.Message) any {{ return from{name}(value.(*pb.{name})) }},
  newMessage: func() proto.Message {{ return &pb.{name}{{}} }},
 }},
""")
    registry.append("}\n")
    (base / "protobuf/registry_generated.go").write_text(explicit_names("".join(registry), True))
