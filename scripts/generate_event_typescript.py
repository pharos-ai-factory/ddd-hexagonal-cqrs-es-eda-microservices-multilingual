"""Generate plain TypeScript contracts and the schema-driven adaptor registry."""

import json

HEADER = "// Generated by scripts/generate_events.py. DO NOT EDIT.\n"


def generate(root, messages, events):
    base = root / "services/engagement/src"
    (base / "adaptors/generated").mkdir(parents=True, exist_ok=True)
    directory = base / "contracts/events"
    directory.mkdir(parents=True, exist_ok=True)
    for path in directory.glob("*.ts"):
        path.unlink()
    for owner in sorted({m["owner"] for m in messages}):
        owned = [m for m in messages if m["owner"] == owner]
        lines = [HEADER]
        for m in messages:
            if m["owner"] != owner and any(
                f["message"] == m["type"] for item in owned for f in item["fields"]
            ):
                lines.append(f"import type {{{m['name']}}} from './{m['owner']}.js';\n")
        for m in owned:
            lines.append(
                f"\n/** Published {m['name']} data owned by {owner}. */\nexport type {m['name']} = {{\n"
            )
            for f in m["fields"]:
                typ = (
                    f["message"].split(".")[-1]
                    if f["type"] == 11
                    else {9: "string", 8: "boolean"}.get(f["type"], "number")
                )
                lines.append(f"  {f['json']}: {typ}{'[]' if f['repeated'] else ''};\n")
            lines.append("};\n")
        (directory / (owner + ".ts")).write_text("".join(lines))
    lines = [HEADER, "import type {Publication} from '../../foundation/application.js';\n"]
    for e in events:
        lines.append(
            f"import type {{{e['type'].split('.')[-1]}}} from '../../contracts/events/{e['owner']}.js';\n"
        )
    lines.append("\nexport type PublishedEventPayloads = {\n")
    for e in events:
        lines.append(f"  '{e['name']}': {e['type'].split('.')[-1]};\n")
    lines.append("};\n")
    lines.append(
        "\n/** Bind a published name to its generated plain payload. */\n"
        "export function published<K extends keyof PublishedEventPayloads>(name: K, payload: NoInfer<PublishedEventPayloads[K]>): Publication {\n"
        "  return {name, payload};\n}\n"
    )
    (base / "adaptors/generated/event-types.ts").write_text("".join(lines))
    (base / "adaptors/generated/event-contracts.json").write_text(
        json.dumps({"events": events, "messages": messages}, indent=2) + "\n"
    )
