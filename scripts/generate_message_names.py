"""Generate event, subscription and private command identifiers from owner catalogues."""

from collections import defaultdict
from pathlib import Path
import json
import re
import subprocess
import sys
from contract_sources import catalogue, subscriptions
from private_command_names import read as private_commands

ROOT = Path(__file__).resolve().parents[1]


def symbol(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name.replace("-", "_")).upper()


def message_names(service, root=ROOT):
    result = defaultdict(dict)
    private = {
        "storefront": ("menu", "ordering"),
        "operations": ("preparation", "collection"),
        "engagement": ("loyalty", "communication"),
    }[service]
    for event in catalogue(service, root):
        role = "DomainEvent" if event["visibility"] == "domain" else "IntegrationEvent"
        key = event["name"].split(".", 1)[1].removesuffix(".domain")
        result[event["owner"]].setdefault(role, []).append((symbol(key), event["name"]))
    for sub in subscriptions(root):
        owner, key = sub["consumer"].split(".", 1)
        if owner not in private:
            continue
        result[owner].setdefault("Subscription", []).append((symbol(key), sub["consumer"]))
    for owner in private:
        fields = private_commands(owner, root)
        if fields:
            result[owner]["PrivateCommand"] = [
                (field.upper(), field if service == "operations" else name) for field, name in fields
            ]
        declared = {
            sub["command"]
            for sub in subscriptions(root)
            if sub["consumer"].startswith(owner + ".") and "command" in sub
        }
        if not declared <= {name for _, name in fields}:
            raise ValueError("Subscription names an unknown private command: " + owner)
    return {
        owner: {kind: sorted(fields) for kind, fields in sorted(kinds.items())}
        for owner, kinds in sorted(result.items())
    }


def render(catalogue, language):
    roles = ("IntegrationEvent", "DomainEvent", "Subscription", "PrivateCommand")
    if language == "go":
        lines = ["// Code generated by scripts/generate_message_names.py. DO NOT EDIT.", "package names"]
        for role in roles:
            lines.append(
                f"type {role}Name interface {{ {role[0].lower() + role[1:]}Name(); String() string; Owner() string }}"
            )
        for owner, kinds in catalogue.items():
            for role, fields in kinds.items():
                typename = owner.title() + role
                lines += [f"type {typename} string", "const ("]
                lines += [
                    f"{typename}{''.join(part.title() for part in field.split('_'))} {typename} = {json.dumps(value)}"
                    for field, value in fields
                ]
                lines += [
                    ")",
                    f"func ({typename}) {role[0].lower() + role[1:]}Name() {{}}",
                    f"func (v {typename}) String() string {{ return string(v) }}",
                    f'func ({typename}) Owner() string {{ return "{owner}" }}',
                ]
        return "\n".join(lines) + "\n"
    lines = (
        [
            "# Generated by scripts/generate_message_names.py. DO NOT EDIT.",
            "from enum import StrEnum",
            "from typing import Never",
        ]
        if language == "python"
        else ["// Generated by scripts/generate_message_names.py. DO NOT EDIT."]
    )
    for owner, kinds in catalogue.items():
        for role, fields in kinds.items():
            name = owner.title() + role
            if language == "python":
                lines += [f"class {name}(StrEnum):"] + [f"    {field} = {value!r}" for field, value in fields]
            else:
                lines += (
                    [f"export enum {name} {{"]
                    + [f"  {field} = {value!r}," for field, value in fields]
                    + ["}"]
                )
    for role in roles:
        variants = [owner.title() + role for owner, kinds in catalogue.items() if role in kinds]
        union = " | ".join(variants) or ("Never" if language == "python" else "never")
        lines += [
            f"type {role}Name = {union}" if language == "python" else f"export type {role}Name = {union};"
        ]
    lines += [
        "type EventName = IntegrationEventName | DomainEventName"
        if language == "python"
        else "export type EventName = IntegrationEventName | DomainEventName;"
    ]
    return "\n".join(lines) + "\n"


def generate(root=ROOT):
    for service, language, target in (
        ("storefront", "go", "services/storefront/contracts/events/names/names_generated.go"),
        ("operations", "python", "services/operations/src/operations/adaptors/generated/message_names.py"),
        ("engagement", "typescript", "services/engagement/src/adaptors/generated/message-names.ts"),
    ):
        path = root / target
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(message_names(service, root), language))
        if language == "go":
            subprocess.run(
                [sys.executable, str(ROOT / "scripts/go.py"), "gofmt", "-w", str(path)], check=True
            )


if __name__ == "__main__":
    generate()
