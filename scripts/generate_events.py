"""Generate published DTOs and typed payload bindings from context-owned schemas."""

from pathlib import Path
import subprocess
import sys
from contract_selection import owners
from event_contracts import load
from generate_event_go import generate as go
from generate_event_python import generate as python
from generate_event_typescript import generate as typescript
from contract_sources import PRIVATE, catalogue, CONTEXT_PATHS


def generate(root=Path(__file__).resolve().parents[1]):
    schema = load(root)
    for service, target in (("storefront", go), ("operations", python), ("engagement", typescript)):
        selected = owners(service, "events", root)
        events = [e for e in schema["events"] if e["owner"] in selected]
        messages = {m["type"]: m for m in schema["messages"]}
        needed = {m["type"] for m in schema["messages"] if m["owner"] in selected}
        pending = list(needed)
        while pending:
            for field in messages[pending.pop()]["fields"]:
                if field["message"] and field["message"] not in needed:
                    needed.add(field["message"])
                    pending.append(field["message"])
        target(root, [m for m in schema["messages"] if m["type"] in needed], events)
    module = "github.com/pharos-ai-factory/ddd-hexagonal-cqrs-es-eda-microservices-multilingual/services/storefront"
    private_go = {owner: path for owner, path in PRIVATE.items() if path.startswith("services/storefront/")}
    code = "// Code generated by scripts/generate_events.py. DO NOT EDIT.\npackage protobuf\nimport (\n"
    code += "".join(
        f'{owner} "{module}/contexts/{owner}/adaptors/messaging/events"\n' for owner in private_go
    )
    code += ")\nvar privateCodecs = map[string]privateCodec{\n"
    code += "".join(
        f'"{owner}": {{encode: {owner}.EncodePrivateEvent, decode: {owner}.DecodePrivateEvent}},\n'
        for owner in private_go
    )
    code += "}\n"
    (root / "services/storefront/contracts/events/protobuf/private_registry_generated.go").write_text(code)
    private_ts = {owner: path for owner, path in PRIVATE.items() if path.startswith("services/engagement/")}
    code = "// Generated by scripts/generate_events.py. DO NOT EDIT.\n"
    code += "import type {PrivateEventCodec} from '../private-event.js';\n"
    code += "".join(
        f"import {{privateEventCodec as {owner}}} from '../../contexts/{owner}/adaptors/messaging/private-event-codec.js';\n"
        for owner in private_ts
    )
    code += "".join(
        f"import type {{PrivateEventPayloads as {owner.title()}Payloads}} from '../../contexts/{owner}/adaptors/messaging/private-event-codec.js';\n"
        for owner in private_ts
    )
    code += (
        "export type PrivateEventPayloads = "
        + " & ".join(owner.title() + "Payloads" for owner in private_ts)
        + ";\n"
    )
    code += (
        "export const privateCodecs: Readonly<Record<string, PrivateEventCodec>> = {"
        + ", ".join(private_ts)
        + "};\n"
    )
    (root / "services/engagement/src/adaptors/generated/private-event-registry.ts").write_text(code)
    topology = catalogue("topology", root)
    code = "// Code generated by scripts/generate_events.py. DO NOT EDIT.\npackage support\n"
    code += f'import broker "{module}/foundation/transport/amqp"\n'
    code += "var expectedSubscriptions = map[string]broker.Binding{\n"
    for item in topology:
        owner = item["consumer"].split(".")[0]
        if owner in ("menu", "ordering"):
            code += f'"{item["consumer"]}": {{Consumer:"{item["consumer"]}",Event:"{item["name"]}",Visibility:"{item["visibility"]}",Context:"{owner}"}},\n'
    code += "}\n"
    destination = root / "services/storefront/apps/support/subscriptions_generated.go"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(code)
    for owner in ("menu", "ordering"):
        code = "// Code generated by scripts/generate_events.py. DO NOT EDIT.\npackage messaging\n"
        code += f'import broker "{module}/foundation/transport/amqp"\n'
        code += "\n// Subscription resolves a consumer-owned declaration at composition.\nfunc Subscription(consumer string) broker.Binding {\n switch consumer {\n"
        for item in topology:
            if item["consumer"].startswith(owner + "."):
                code += f'case "{item["consumer"]}": return broker.Binding{{Consumer: consumer, Event: "{item["name"]}", Visibility: "{item["visibility"]}", Context: "{owner}"}}\n'
        code += '}\n panic("undeclared subscription: " + consumer)\n}\n'
        (root / CONTEXT_PATHS[owner] / "subscriptions_generated.go").write_text(code)
    paths = [
        destination,
        *root.glob("services/storefront/contracts/events/**/*_generated.go"),
        *root.glob("services/storefront/contexts/*/adaptors/messaging/subscriptions_generated.go"),
    ]
    subprocess.run(
        [sys.executable, str(Path(__file__).with_name("go.py")), "gofmt", "-w", *map(str, paths)], check=True
    )


if __name__ == "__main__":
    generate()
