"""Generate plain TypeScript command/query types and schema-shaped boundary parsers."""

HEADER = "// Code generated by scripts/generate_request_payloads.py. DO NOT EDIT.\n"


def generate(root, owner, messages):
    shared = owner == "shared"
    types = [HEADER]
    if not shared:
        types += ["import type { PageRequest } from './shared.js';\n"]
    codecs = [
        HEADER,
        "import { record, text, integer, boolean } from '../../../../../adaptors/messaging/request-values.js';\n",
        f"import type {{ {', '.join(m['name'] for m in messages)} }} from '../../../../../contracts/requests/generated/{owner}.js';\n",
        "import type { PageRequest } from '../../../../../contracts/requests/generated/shared.js';\n",
    ]
    for m in messages:
        types += [
            f"/** Schema-defined {m['visibility'].lower()} {m['role'].lower()} payload. */\n",
            f"export type {m['name']} = Readonly<{{\n",
        ]
        for f in m["fields"]:
            typ = {
                3: "number",
                4: "number",
                5: "number",
                8: "boolean",
                9: "string",
                11: "PageRequest",
                13: "number",
            }[f["type"]]
            types += [
                f" {f['json']}{'?' if f['optional'] else ''}: {typ}{' | undefined' if f['optional'] else ''};\n"
            ]
        types += ["}>;\n"]
        if shared:
            continue
        codecs += [
            f"export function parse{m['name']}(value: unknown): {m['name']} {{\n const fields = record(value);\n return {{\n"
        ]
        for f in m["fields"]:
            access = "fields." + f["json"]
            if not f["presence"]:
                default = "''" if f["type"] == 9 else ("false" if f["type"] == 8 else "0")
                access = f"({access} === undefined ? {default} : {access})"
            if f["type"] == 11:
                expression = f"page({access})"
            elif f["type"] == 9:
                expression = f"text({access})"
            elif f["type"] == 8:
                expression = f"boolean({access})"
            else:
                lo, hi = {
                    3: (-(2**53 - 1), 2**53 - 1),
                    4: (0, 2**53 - 1),
                    5: (-(2**31), 2**31 - 1),
                    13: (0, 2**32 - 1),
                }[f["type"]]
                expression = f"bounded({access}, {lo}, {hi})"
            if f["optional"]:
                codecs += [
                    f" ...(fields.{f['json']} !== undefined ? {{ {f['json']}: {expression} }} : {{}}),\n"
                ]
            else:
                codecs += [f" {f['json']}: {expression},\n"]
        codecs += [" };\n}\n"]
    base = root / "services/engagement/src/contracts/requests/generated"
    base.mkdir(parents=True, exist_ok=True)
    (base / f"{owner}.ts").write_text("".join(types))
    if not shared:
        codecs += [
            "function bounded(value: unknown, minimum: number, maximum: number): number {\n",
            ' const result = integer(value); if (result < minimum || result > maximum) throw new Error("Integer outside schema range"); return result;\n}\n',
            "function page(value: unknown): PageRequest {\n const fields = record(value); return { limit: bounded(fields.limit ?? 0, 0, 4294967295), ...(fields.after !== undefined ? {after: text(fields.after)} : {}) };\n}\n",
        ]
        path = (
            root
            / f"services/engagement/src/contexts/{owner}/adaptors/messaging/generated/request-payloads.ts"
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("".join(codecs))
