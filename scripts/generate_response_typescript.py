"""Generate plain TypeScript replies, checked encoders and typed query bindings."""

from generate_request_python import snake

HEADER = "// Code generated by scripts/generate_response_payloads.py. DO NOT EDIT.\n"


def generate(root, owner, messages, requests, catalogue):
    shared = owner == "shared"
    models = [HEADER]
    if not shared:
        models += ["import type { Outcome, RequestError } from './shared-responses.js';\n"]
    codecs = [
        HEADER,
        f"import type {{ {owner} as wire }} from '{'../../generated' if shared else '../../../../../adaptors/generated'}/request-types.js';\n",
        f"import {{ text, integer, boolean }} from '{'../request-values.js' if shared else '../../../../../adaptors/messaging/request-values.js'}';\n",
        f"import type {{ {', '.join([m['name'] for m in messages] + [r['name'].removesuffix(r['role']) + 'Response' for r in requests])} }} from '{'../../../contracts' if shared else '../../../../../contracts'}/requests/generated/{owner}-responses.js';\n",
    ]
    if not shared:
        codecs += [
            "import { toRequestError } from '../../../../../adaptors/messaging/generated/response-payloads.js';\n",
            "import type { RabbitMQRequestRegistry } from '../../../../../adaptors/messaging/rabbitmq-request-registry.js';\n",
            f"import {{ {owner.title()}Query }} from '../../../../../adaptors/generated/request-names.js';\n",
            f"import type {{ {', '.join(r['name'] for r in requests if r['role'] == 'Query')} }} from '../../../../../contracts/requests/generated/{owner}.js';\n",
        ]
    if not shared:
        dependencies = {
            catalogue[f["target"]]["name"]
            for m in messages
            for f in m["fields"]
            if f["type"] == 11 and catalogue[f["target"]]["owner"] == "shared"
        }
        for name in sorted(dependencies):
            models += [f"import type {{ {name} }} from './shared-responses.js';\n"]
            codecs += [
                f"import {{ to{name} }} from '../../../../../adaptors/messaging/generated/response-payloads.js';\n"
            ]
    for m in messages:
        name = m["name"]
        models += [f"/** Schema-generated plain response payload. */\nexport type {name} = {{\n"]
        codecs += [f"export function to{name}(value: {name}): wire.{name} {{\n return {{\n"]
        for f in m["fields"]:
            typ = {3: "number", 4: "number", 5: "number", 8: "boolean", 9: "string", 13: "number"}.get(
                f["type"]
            )
            if f["type"] == 11:
                typ = catalogue[f["target"]]["name"]
            if f["repeated"]:
                typ += "[]"
            models += [f" {f['json']}{'?' if f['optional'] else ''}: {typ};\n"]
            expr = "item" if f["repeated"] else f"value.{f['json']}"
            if f["type"] == 11:
                expr = f"to{catalogue[f['target']]['name']}({expr})"
            elif f["type"] in (9, 8):
                expr = f"{'text' if f['type'] == 9 else 'boolean'}({expr})"
            else:
                lo, hi = {
                    3: (-(2**53 - 1), 2**53 - 1),
                    4: (0, 2**53 - 1),
                    5: (-(2**31), 2**31 - 1),
                    13: (0, 2**32 - 1),
                }[f["type"]]
                expr = f"bounded({expr}, {lo}, {hi})"
            if f["repeated"]:
                expr = f"value.{f['json']}.map((item) => {expr})"
            if f["optional"]:
                codecs += [f" ...(value.{f['json']} !== undefined ? {{ {f['json']}: {expr} }} : {{}}),\n"]
            else:
                codecs += [f" {f['json']}: {expr},\n"]
        models += ["};\n"]
        codecs += [" };\n}\n"]
    for req in requests:
        name = req["name"].removesuffix(req["role"]) + "Response"
        if req["role"] == "Command":
            models += [f"export type {name} = Outcome;\n"]
            continue
        key = req["response_json"]
        target = catalogue[req["response"]]["name"]
        action = req["wire_name"]
        models += [
            f"export type {name} = {{ {key}: {target}; error?: never }} | {{ error: RequestError; {key}?: never }};\n"
        ]
        codecs += [
            f"export function encode{action}Response(_query: {req['name']}, value: {name}) {{\n",
            f" if ((value.{key} !== undefined) === (value.error !== undefined)) throw new Error('Select exactly one {name} alternative');\n",
            f" return value.{key} !== undefined ? {{ {key}: to{target}(value.{key}) }} : {{ error: toRequestError(value.error!) }};\n}}\n",
            f"/** Bind the schema's request, result and reply encoder. */\nexport function register{action}(registry: RabbitMQRequestRegistry, parse: (value: unknown) => {req['name']}, handler: {{ execute(query: {req['name']}): Promise<{name}> }}) {{\n",
            f" registry.query({owner.title()}Query.{snake(action).upper()}, parse, handler, encode{action}Response);\n}}\n",
        ]
    codecs += [
        "function bounded(value: unknown, minimum: number, maximum: number): number {\n const result = integer(value); if (result < minimum || result > maximum) throw new Error('Integer outside schema range'); return result;\n}\n"
    ]
    # Generated files are also checked for unused imports.
    source = "".join(codecs)
    import re

    def prune(match):
        names = [
            v.strip()
            for v in match[2].split(",")
            if len(re.findall(r"\b" + re.escape(v.strip()) + r"\b", source)) > 1
        ]
        return f"import {match[1]}{{ {', '.join(names)} }} from {match[3]};" if names else ""

    source = re.sub(
        r"import (type )?\{ ([^{}]+) \} from ([^;]+);",
        lambda m: prune((m[0], m[1] or "", m[2], m[3])) if " as " not in m[2] else m[0],
        source,
    )
    base = root / "services/engagement/src/contracts/requests/generated"
    base.mkdir(parents=True, exist_ok=True)
    (base / f"{owner}-responses.ts").write_text("".join(models))
    dest = root / (
        "services/engagement/src/adaptors/messaging/generated/response-payloads.ts"
        if shared
        else f"services/engagement/src/contexts/{owner}/adaptors/messaging/generated/response-payloads.ts"
    )
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(source)
