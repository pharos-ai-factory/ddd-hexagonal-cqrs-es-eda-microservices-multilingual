"""Generate scoped request identifiers from compiled Protobuf payload oneofs."""

from pathlib import Path
import subprocess
import sys
from contract_selection import owners
from protobuf_selection import compile_descriptors

ROOT = Path(__file__).resolve().parents[1]


def request_names(descriptors):
    result = {}
    for file in descriptors.file:
        if not file.name.endswith("_requests.proto"):
            continue
        owner = file.package.split(".")[1]
        result[owner] = {}
        for message in file.message_type:
            if message.name not in ("Command", "Query"):
                continue
            payload = next(i for i, oneof in enumerate(message.oneof_decl) if oneof.name == "payload")
            result[owner][message.name] = [
                (field.name, field.json_name)
                for field in message.field
                if field.HasField("oneof_index") and field.oneof_index == payload
            ]
    return result


def python_names(catalogue):
    lines = [
        "# Generated by scripts/generate_request_names.py. DO NOT EDIT.",
        "from enum import StrEnum",
        "from typing import Never",
    ]
    for owner, kinds in catalogue.items():
        for kind, fields in kinds.items():
            lines += [f"class {owner.title()}{kind}(StrEnum):"]
            lines += [f"    {field.upper()} = {name!r}" for field, name in fields] or ["    pass"]
    for kind in ("Command", "Query"):
        variants = [owner.title() + kind for owner, kinds in catalogue.items() if kind in kinds]
        lines += [f"type {kind}Name = " + (" | ".join(variants) or "Never")]
        lines += [f"{kind.upper()}_TYPES: dict[str, type[{kind}Name]] = {{"]
        lines += [
            f"    {owner!r}: {owner.title()}{kind}," for owner, kinds in catalogue.items() if kind in kinds
        ]
        lines += ["}"]
    return "\n".join(lines) + "\n"


def typescript_names(catalogue):
    lines = ["// Generated by scripts/generate_request_names.py. DO NOT EDIT."]
    for owner, kinds in catalogue.items():
        for kind, fields in kinds.items():
            lines += [f"export enum {owner.title()}{kind} {{"]
            lines += [f"  {field.upper()} = {name!r}," for field, name in fields]
            lines += ["}"]
    for kind in ("Command", "Query"):
        variants = [owner.title() + kind for owner, kinds in catalogue.items() if kind in kinds]
        lines += [f"export type {kind}Name = " + (" | ".join(variants) or "never") + ";"]
        lines += [f"export const {kind.upper()}_NAMES: Readonly<Record<string, readonly {kind}Name[]>> = {{"]
        lines += [
            f"  {owner}: Object.values({owner.title()}{kind}),"
            for owner, kinds in catalogue.items()
            if kind in kinds
        ]
        lines += ["};"]
    return "\n".join(lines) + "\n"


def go_names(catalogue):
    lines = ["// Code generated by scripts/generate_request_names.py. DO NOT EDIT.", "package requestsv1"]
    for kind in ("Command", "Query"):
        lines += [
            f"type {kind}Name interface {{ {kind.lower()}Name(); Owner() string; String() string; Valid() bool }}"
        ]
    for owner, kinds in catalogue.items():
        for kind, fields in kinds.items():
            typename = owner.title() + kind
            lines += [f"type {typename} string", "const ("]
            lines += [
                f'{typename}{"".join(part.title() for part in field.split("_"))} {typename} = "{name}"'
                for field, name in fields
            ]
            lines += [
                ")",
                f"func ({typename}) {kind.lower()}Name() {{}}",
                f'func ({typename}) Owner() string {{ return "{owner}" }}',
                f"func (n {typename}) String() string {{ return string(n) }}",
                f"func (n {typename}) Valid() bool {{ switch n {{",
            ]
            if fields:
                constants = [
                    typename + "".join(part.title() for part in field.split("_")) for field, _ in fields
                ]
                lines += ["case " + ", ".join(constants) + ": return true"]
            lines += ["}; return false }"]
    return "\n".join(lines) + "\n"


def generate(root=ROOT):
    catalogue = request_names(compile_descriptors("requests", root))
    for service in ("storefront", "api", "operations", "engagement"):
        selected = {owner: catalogue[owner] for owner in sorted(owners(service, "requests", root))}
        if service in ("storefront", "api"):
            base = (
                "contracts/requests/generated" if service == "storefront" else "adaptors/messaging/generated"
            )
            path = root / f"services/{service}/{base}/cafe/requests/v1/names.go"
            code = go_names(selected)
        elif service == "operations":
            path = root / "services/operations/src/operations/adaptors/generated/request_names.py"
            code = python_names(selected)
        else:
            path = root / "services/engagement/src/adaptors/generated/request-names.ts"
            code = typescript_names(selected)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(code)
        if path.suffix == ".go":
            subprocess.run(
                [sys.executable, str(ROOT / "scripts/go.py"), "gofmt", "-w", str(path)], check=True
            )


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    generate(parser.parse_args().root)
