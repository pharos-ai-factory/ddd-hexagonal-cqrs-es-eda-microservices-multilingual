"""Generate plain Python reply DTOs, checked encoders and typed query bindings."""

from generate_request_python import clean_imports, snake

HEADER = "# Generated by scripts/generate_response_payloads.py. DO NOT EDIT.\n"


def generate(root, owner, messages, requests, catalogue):
    shared = owner == "shared"
    models = [HEADER, "from typing import TypedDict, NotRequired\n"]
    if not shared:
        models += [
            "from operations.contracts.requests.generated.shared_responses import Outcome, RequestError\n"
        ]
    codecs = [
        HEADER,
        "from collections.abc import Callable\n",
        "from typing import cast\n",
        "from operations.adaptors.messaging.request_values import string_value, integer_value, boolean_value\n",
        f"from operations.contracts.requests.generated.{owner}_responses import "
        + ", ".join(
            [m["name"] for m in messages] + [r["name"].removesuffix(r["role"]) + "Response" for r in requests]
        )
        + "\n",
    ]
    if not shared:
        codecs += [
            "from operations.adaptors.messaging.generated.response_payloads import to_request_error\n",
            "from google.protobuf.message import Message\n",
            "from operations.adaptors.messaging.rabbitmq_request_registry import RabbitMQRequestRegistry\n",
            f"from operations.adaptors.generated.request_names import {owner.title()}Query\n",
            f"from operations.contracts.requests.generated.{owner} import "
            + ", ".join(r["name"] for r in requests if r["role"] == "Query")
            + "\n",
            f"from operations.adaptors.generated.cafe.requests.v1.contexts.{owner}.{owner}_requests_pb2 import Reply\n",
        ]
    if not shared:
        dependencies = {
            catalogue[f["target"]]["name"]
            for m in messages
            for f in m["fields"]
            if f["type"] == 11 and catalogue[f["target"]]["owner"] == "shared"
        }
        for name in sorted(dependencies):
            models += [f"from operations.contracts.requests.generated.shared_responses import {name}\n"]
            codecs += [
                f"from operations.adaptors.messaging.generated.response_payloads import to_{snake(name)}\n"
            ]
    module = (
        "operations.adaptors.generated.cafe.requests.v1.common_pb2"
        if shared
        else f"operations.adaptors.generated.cafe.requests.v1.contexts.{owner}.{owner}_replies_pb2"
    )
    for m in messages:
        name = m["name"]
        models += [f'\nclass {name}(TypedDict):\n    """Schema-generated plain response payload."""\n']
        codecs += [f"from {module} import {name} as Wire{name}\n"]
        for f in m["fields"]:
            typ = {3: "int", 4: "int", 5: "int", 8: "bool", 9: "str", 13: "int"}.get(f["type"])
            if f["type"] == 11:
                typ = catalogue[f["target"]]["name"]
            if f["repeated"]:
                typ = f"list[{typ}]"
            if f["optional"]:
                typ = f"NotRequired[{typ}]"
            models += [f"    {f['json']}: {typ}\n"]
        codecs += [f"\ndef to_{snake(name)}(value: {name}) -> Wire{name}:\n    result = Wire{name}()\n"]
        for f in m["fields"]:
            key = f["json"]
            indent = "    "
            if f["optional"]:
                codecs += [f"    if {key!r} in value:\n"]
                indent += "    "
            expr = f"value[{key!r}]"
            if f["repeated"]:
                codecs += [f"{indent}for item in {expr}:\n"]
                indent += "    "
                expr = "item"
            if f["type"] == 11:
                expr = f"to_{snake(catalogue[f['target']]['name'])}({expr})"
            elif f["type"] in (9, 8):
                expr = f"{'string_value' if f['type'] == 9 else 'boolean_value'}({expr})"
            else:
                lo, hi = {
                    3: (-(2**53 - 1), 2**53 - 1),
                    4: (0, 2**53 - 1),
                    5: (-(2**31), 2**31 - 1),
                    13: (0, 2**32 - 1),
                }[f["type"]]
                expr = f"integer_value({expr}, {lo}, {hi})"
            if f["repeated"]:
                statement = f"result.{f['name']}.append({expr})"
            elif f["type"] == 11:
                statement = f"result.{f['name']}.CopyFrom({expr})"
            else:
                statement = f"result.{f['name']} = {expr}"
            codecs += [indent + statement + "\n"]
        codecs += ["    return result\n"]
    for req in requests:
        action = req["wire_name"]
        response = req["name"].removesuffix(req["role"]) + "Response"
        if req["role"] == "Command":
            models += [f"\n{response} = Outcome\n"]
            continue
        target = catalogue[req["response"]]["name"]
        key = req["response_json"]
        codecs += [
            f"from operations.contracts.requests.generated.{owner}_responses import {action}Success, {action}Failure\n"
        ]
        models += [
            f"\nclass {action}Success(TypedDict):\n    {key}: {target}\n",
            f"\nclass {action}Failure(TypedDict):\n    error: RequestError\n",
            f"\n{response} = {action}Success | {action}Failure\n",
        ]
        codecs += [
            f"\ndef encode_{snake(action)}_response(_query: {req['name']}, value: {response}) -> Reply:\n",
            f"    if ({key!r} in value) == ('error' in value):\n        raise ValueError('Select exactly one {response} alternative')\n",
            f"    if isinstance(value, dict) and {key!r} in value:\n        return Reply({req['response_field']}=to_{snake(target)}(cast({action}Success, value)[{key!r}]))\n",
            "    return Reply(error=to_request_error(value['error']))\n",
            f"\ndef register_{snake(action)}(registry: RabbitMQRequestRegistry, parse: Callable[[Message], {req['name']}], execute: Callable[[{req['name']}], {response}]) -> None:\n",
            f"    registry.query({owner.title()}Query.{snake(action).upper()}, parse, execute, encode_{snake(action)}_response)\n",
        ]
    base = root / "services/operations/src/operations/contracts/requests/generated"
    base.mkdir(parents=True, exist_ok=True)
    (base / f"{owner}_responses.py").write_text(clean_imports("".join(models)))
    dest = root / (
        "services/operations/src/operations/adaptors/messaging/generated/response_payloads.py"
        if shared
        else f"services/operations/src/operations/contexts/{owner}/adaptors/messaging/generated/response_payloads.py"
    )
    dest.parent.mkdir(parents=True, exist_ok=True)
    lines = "".join(codecs).splitlines()
    imports = [line for line in lines if line.startswith("from ")]
    body = [line for line in lines[1:] if not line.startswith("from ")]
    dest.write_text(clean_imports(HEADER + "\n".join([*imports, *body]) + "\n"))
